"""
Предмет находки — то, о чём она, — отдельно от текста сообщения.

Текст для человека укорочен: «/a, /b, /c и ещё 2», «совпадает с X и ещё 1».
Сравнение с базовой линией раньше вынимало предмет регулярным выражением из
этого текста и видело только первые три адреса: новая битая ссылка, которая
сортировалась четвёртой, не замечалась, а исправленная первая выдвигала
четвёртую на свет и выглядела новой находкой.

`Said` — это та же строка сообщения, к которой приложен полный предмет. Она
проходит через кортежи находок без изменений, а в JSON прогона предмет
пишется отдельным полем `subject`.
"""


class Said(str):
    """Строка сообщения с полным предметом находки (`subject`)."""

    def __new__(cls, text, subject=()):
        self = super().__new__(cls, text)
        self.subject = tuple(sorted({str(s) for s in subject}))
        return self

    def __reduce__(self):
        # Параллельный разбор шлёт находки между процессами.
        return (Said, (str(self), self.subject))


def subject_of(message):
    """Полный предмет, если он приложен к сообщению, иначе None."""
    return getattr(message, "subject", None)
