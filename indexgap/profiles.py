DEFAULT_PROFILE = "catalog"


def get(name: str) -> dict:
    """Профиль по имени. Неизвестное имя — ошибка, а не молчаливый дефолт."""
    from .core import SourceError

    key = (name or DEFAULT_PROFILE).strip().lower()
    if key not in PROFILES:
        raise SourceError(
            tr("Профиль «{a0}» неизвестен. Доступны: ", a0=name)
            + ", ".join(sorted(PROFILES))
            + tr("\n    Что они значат — в README, раздел «Профили»."))
    return PROFILES[key]


def apply(config: dict, name: str) -> dict:
    """
    Накладывает профиль на настройки проекта.

    Порядок важен: профиль ниже того, что человек написал руками.
    Явная настройка в `indexgap.json` всегда сильнее пресета.
    """
    from .core import SourceError

    profile = get(name)
    out = dict(config or {})
    for section in ("checks", "content", "aeo"):
        value = out.get(section)
        if value is not None and not isinstance(value, dict):
            raise SourceError(
                tr("В настройках проекта раздел `{a0}` должен быть объектом с порогами, а не {a1}.\n    Путь к страницам записывается полем `pages`, не `content` — поправь indexgap.json.", a0=section, a1=type(value).__name__))
        merged = dict(profile.get(section) or {})
        merged.update(value or {})
        out[section] = merged
    out["_profile"] = (name or DEFAULT_PROFILE).strip().lower()
    out["_profile_title"] = profile["title"]
    out["_profile_notes"] = profile["notes"]
    out["_expects_dataset"] = profile.get("expects_dataset", True)
    out["_skip_facts"] = profile.get("skip_facts", False)
    out["_checks_freshness"] = profile.get("checks_freshness", False)
    return out


def describe(name: str) -> str:
    profile = get(name)
    changed = []
    for section in ("checks", "content", "aeo"):
        for key, value in sorted((profile.get(section) or {}).items()):
            changed.append(f"{key}={value}")
    return f"{profile['title']}: " + ", ".join(changed) if changed else profile["title"]
